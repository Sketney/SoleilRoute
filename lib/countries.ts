function normalizeSearch(value: string) {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^\x20-\x7E]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

function displayNameForCode(code: string, locale = "en") {
  const fallback = new Intl.DisplayNames(["en"], { type: "region" }).of(code);
  return (
    new Intl.DisplayNames([locale, "en"], { type: "region" }).of(code) ??
    fallback ??
    code
  );
}

export function countryCodeToName(code: string, locale = "en") {
  const normalizedCode = code.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(normalizedCode)) {
    return null;
  }
  return displayNameForCode(normalizedCode, locale);
}

export function countryNameToCode(value: string) {
  const normalized = normalizeSearch(value);
  const directCode = value.trim().toUpperCase();
  if (
    /^[A-Z]{2}$/.test(directCode) &&
    (iso2CountryCodes as readonly string[]).includes(directCode)
  ) {
    return directCode;
  }
  if (countryAliases[normalized]) {
    return countryAliases[normalized];
  }

  for (const code of iso2CountryCodes) {
    if (normalizeSearch(displayNameForCode(code)) === normalized) {
      return code;
    }
  }

  return null;
}

export function getCountryOptions(locale = "en"): CountryOption[] {
  return iso2CountryCodes
    .map((code) => {
      const name = displayNameForCode(code, locale);
      const englishName = displayNameForCode(code, "en");
      return {
        code,
        name,
        search: `${normalizeSearch(name)} ${normalizeSearch(englishName)} ${code.toLowerCase()}`,
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name, locale));
}
